const TITLES: Record<string, string> = {
  es: 'InventaFactura — Facturación e inventario en móvil y PC',
  en: 'InventaFactura — Invoicing & inventory on mobile and PC',
};

const LANG_KEY = 'inventafactura-lang';
let currentLang = localStorage.getItem(LANG_KEY) || 'es';

export function applyLang(lang: string) {
  currentLang = lang;
  document.documentElement.lang = lang;
  document.title = TITLES[lang];

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = (el as HTMLElement).dataset.i18n ?? '';
    if (I18N[lang] && I18N[lang][key] !== undefined) {
      el.textContent = I18N[lang][key];
    }
  });

  const label = document.getElementById('langLabel');
  if (label) label.textContent = lang === 'es' ? 'EN' : 'ES';

  localStorage.setItem(LANG_KEY, lang);
}

export function initI18n() {
  const toggle = document.getElementById('langToggle');
  if (toggle) {
    toggle.addEventListener('click', () => {
      applyLang(currentLang === 'es' ? 'en' : 'es');
    });
  }
  applyLang(currentLang);
}
